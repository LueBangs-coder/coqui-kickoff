export const FORCE_UPDATE_FROM = [
  "coqui-kickoff-static-b1f13d82d61cb513",
  "coqui-kickoff-static-e6b34349a9b3c0a9",
];

export function renderServiceWorker({ version, urls, forceUpdateFrom }) {
  return `/* Generated by scripts/create-sw.mjs. Do not edit dist/sw.js. */
const VERSION = ${JSON.stringify(version)};
const PREFIX = 'coqui-kickoff-static-';
const CACHE = PREFIX + VERSION;
const PRECACHE = ${JSON.stringify(urls)};
const ASSETS = new Set(PRECACHE);
const FORCE_UPDATE_FROM = new Set(${JSON.stringify(forceUpdateFrom)});

self.addEventListener('install', event => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    await cache.addAll(PRECACHE);
    const names = await caches.keys();
    if (names.some(name => FORCE_UPDATE_FROM.has(name))) await self.skipWaiting();
  })());
});

self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    const names = await caches.keys();
    const forceRefresh = names.some(name => FORCE_UPDATE_FROM.has(name));
    await Promise.all(names.filter(name => name.startsWith(PREFIX) && name !== CACHE).map(name => caches.delete(name)));
    await self.clients.claim();
    const windows = await self.clients.matchAll({ type: 'window' });
    windows.forEach(client => client.postMessage({ type: 'COQUI_OFFLINE_READY', version: VERSION }));
    if (forceRefresh) {
      await Promise.allSettled(windows.filter(client => typeof client.navigate === 'function').map(client => client.navigate(client.url)));
    }
  })());
});

self.addEventListener('message', event => {
  if (event.data?.type === 'COQUI_ACTIVATE_UPDATE') {
    event.waitUntil(self.skipWaiting());
  } else if (event.data?.type === 'COQUI_CACHE_STATUS') {
    event.waitUntil(caches.has(CACHE).then(ready => {
      if (ready) event.source?.postMessage({ type: 'COQUI_OFFLINE_READY', version: VERSION });
    }));
  }
});

async function withRange(response, request) {
  const range = request.headers.get('range');
  if (!range) return response;
  // iOS audio playback requests byte ranges even for local, cached recordings.
  const bytes = await response.arrayBuffer();
  const match = /^bytes=(\\d*)-(\\d*)$/.exec(range);
  if (!match || (!match[1] && !match[2])) return new Response(null, { status: 416, headers: { 'Content-Range': 'bytes */' + bytes.byteLength } });
  const start = match[1] ? Number(match[1]) : Math.max(0, bytes.byteLength - Number(match[2]));
  const end = match[1] && match[2] ? Math.min(Number(match[2]), bytes.byteLength - 1) : bytes.byteLength - 1;
  if (!Number.isSafeInteger(start) || !Number.isSafeInteger(end) || start > end || start >= bytes.byteLength) return new Response(null, { status: 416, headers: { 'Content-Range': 'bytes */' + bytes.byteLength } });
  const headers = new Headers(response.headers);
  headers.set('Content-Range', 'bytes ' + start + '-' + end + '/' + bytes.byteLength);
  headers.set('Content-Length', String(end - start + 1));
  headers.set('Accept-Ranges', 'bytes');
  return new Response(bytes.slice(start, end + 1), { status: 206, headers });
}

self.addEventListener('fetch', event => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== 'GET' || url.origin !== self.location.origin) return;
  if (request.mode === 'navigate') {
    // Serve one coherent app version, including all its lazy game/audio chunks.
    event.respondWith((async () => {
      const cache = await caches.open(CACHE);
      return await cache.match('/') || await fetch(request).catch(async () =>
        await cache.match('/offline') || new Response('Open Coquí Kickoff online once to save it for offline practice.', { status: 503, headers: { 'Content-Type': 'text/plain; charset=utf-8' } }));
    })());
    return;
  }
  if (!ASSETS.has(url.pathname)) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    const cached = await cache.match(url.pathname);
    if (cached) return withRange(cached, request);
    return fetch(request);
  })());
});
`;
}
